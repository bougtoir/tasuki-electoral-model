def add_para(text, bold=False, italic=False, align=None, size=None, space_after=None):
    p = doc.add_paragraph()
    parts = re.split(r'(\{[^}]+\})', text)
    for part in parts:
        if part.startswith('{') and part.endswith('}'):
            run = p.add_run(part[1:-1])
            run.font.superscript = True
            if size:
                run.font.size = Pt(size)
            if bold:
                run.bold = True
            if italic:
                run.italic = italic
        else:
            run = p.add_run(part)
            run.bold = bold
            run.italic = italic
            if size:
                run.font.size = Pt(size)
    if align:
        p.alignment = align
    if space_after is not None:
        p.paragraph_format.space_after = Pt(space_after)
    return p


def add_text_para(text):
    """Add paragraph with inline [N] citation references rendered as superscript."""
    p = doc.add_paragraph()
    parts = re.split(r'(\[[0-9, \u2013-]+\])', text)
    for part in parts:
        if re.match(r'^\[[0-9, \u2013-]+\]$', part):
            run = p.add_run(part)
            run.font.superscript = True
            run.font.size = Pt(9)
        else:
            run = p.add_run(part)
    return p


def add_figure(path, caption, width=5.5):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(12)
    run = p.add_run()
    run.add_picture(path, width=Inches(width))
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = cap.add_run(caption)
    r.italic = True
    r.font.size = Pt(10)
    cap.paragraph_format.space_before = Pt(6)
    cap.paragraph_format.space_after = Pt(12)


